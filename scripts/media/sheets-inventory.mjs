/**
 * scripts/media/sheets-inventory.mjs — format the teacher-sheet inventory
 * report (Q1, sheets-inventory.yml).
 *
 * STRUCTURE DISCOVERY ONLY. This never decides a course mapping; it only
 * describes what is in the sheets so the architect can write the mapping after
 * reading the report. It makes no assumptions about which columns mean what —
 * it merely *flags* columns whose header or sample values LOOK like ids/codes,
 * and says so explicitly in the report.
 *
 * The workflow lists every file recursively under the Drive folder, exports each
 * Google Sheet as `.xlsx` (and downloads real `.xlsx` as-is), then dumps every
 * workbook's structure to one JSON array with this shape (per file):
 *
 *   {
 *     "name": "<drive file name>",
 *     "id": "<drive file id>",
 *     "tabs": [
 *       { "name": "<sheet/tab name>",
 *         "header": ["<col A header>", "<col B header>", …],  // first row
 *         "rowCount": <data rows, excluding the header>,
 *         "sample": [ ["r1c1","r1c2",…], ["r2…"], ["r3…"] ]   // up to 3 rows
 *       }, …
 *     ]
 *   }
 *
 * This script turns that JSON into `reports/sheets-inventory.md`. The workbook
 * reading lives in the workflow (a pinned xlsx reader, CI only); the formatting
 * + id-column heuristic live here so they are unit-testable with a fixture.
 *
 * Usage:
 *   node scripts/media/sheets-inventory.mjs <dump.json> > reports/sheets-inventory.md
 *
 * Exit 0 always (a report, never a gate).
 */

import { readFileSync } from 'node:fs';

/**
 * Heuristic: does a column LOOK like an id/code column? Report-only — never a
 * decision. A column is flagged when its header OR a majority of its sample
 * values look id-like:
 *   - header contains "id", "code", "ref", "no", "num", "key" (word-ish), or
 *   - sample values are short tokens of the shape c###, c###-l###, digits, or
 *     an alnum code with no spaces (e.g. a Drive-style long id).
 * The caller sees WHY it was flagged (the reason string), so a human judges it.
 */
export function looksLikeIdColumn(header, sampleValues) {
  const reasons = [];
  const h = String(header ?? '').trim().toLowerCase();
  if (/(^|[^a-z])(id|code|ref|key|no|num|number)([^a-z]|$)/.test(h)) {
    reasons.push(`header "${header}" reads like an id/code`);
  }
  const vals = (sampleValues ?? []).map((v) => String(v ?? '').trim()).filter(Boolean);
  if (vals.length) {
    const idShaped = vals.filter((v) => isIdShaped(v)).length;
    if (idShaped / vals.length >= 0.5) {
      reasons.push(`${idShaped}/${vals.length} sample values are id-shaped`);
    }
  }
  return reasons.length ? reasons.join('; ') : null;
}

/** A single value that looks like an id/code (no spaces, short-ish token). */
export function isIdShaped(v) {
  const s = String(v ?? '').trim();
  if (!s || /\s/.test(s)) return false;
  if (/^c\d{2,}(-l\d{2,}[a-z]?)?$/i.test(s)) return true; // provisional-style c###/c###-l###
  if (/^\d+$/.test(s)) return true; // plain number
  if (/^[A-Za-z0-9_-]{6,}$/.test(s) && /\d/.test(s)) return true; // alnum code w/ a digit
  return false;
}

/** Escape a cell for a Markdown table (pipes and newlines would break the row). */
export function mdCell(v) {
  return String(v ?? '')
    .replace(/\r?\n/g, ' ')
    .replace(/\|/g, '\\|');
}

/** Per-tab id/code column flags: [{ column, header, reason }]. */
export function flagIdColumns(tab) {
  const header = Array.isArray(tab.header) ? tab.header : [];
  const sample = Array.isArray(tab.sample) ? tab.sample : [];
  const flags = [];
  for (let c = 0; c < header.length; c++) {
    const colValues = sample.map((row) => (Array.isArray(row) ? row[c] : undefined));
    const reason = looksLikeIdColumn(header[c], colValues);
    if (reason) flags.push({ column: columnLetter(c), header: header[c], reason });
  }
  return flags;
}

/** 0-based column index → spreadsheet letter (0→A, 25→Z, 26→AA). */
export function columnLetter(index0) {
  let n = index0 + 1;
  let s = '';
  while (n > 0) {
    const r = (n - 1) % 26;
    s = String.fromCharCode(65 + r) + s;
    n = Math.floor((n - 1) / 26);
  }
  return s;
}

/** Build the whole report markdown from the dump array. Pure. */
export function buildReport(files) {
  const list = Array.isArray(files) ? files : [];
  const lines = [];
  lines.push('# Teacher-sheet inventory (Q1 — structure discovery only)');
  lines.push('');
  lines.push(
    'Generated by `sheets-inventory.yml`. This is DISCOVERY ONLY: it describes what is in'
  );
  lines.push(
    'the sheets. It makes no mapping decisions. Columns flagged as id/code are *guesses* for'
  );
  lines.push('a human to confirm — the raw `.xlsx` exports in `data/source/sheets/` are the truth.');
  lines.push('');
  lines.push(`Files found: **${list.length}**.`);
  lines.push('');

  for (const f of list) {
    lines.push(`## ${mdCell(f.name)}`);
    lines.push('');
    lines.push(`- Drive file id: \`${mdCell(f.id)}\``);
    const tabs = Array.isArray(f.tabs) ? f.tabs : [];
    lines.push(`- Tabs: ${tabs.length}`);
    lines.push('');
    for (const tab of tabs) {
      const header = Array.isArray(tab.header) ? tab.header : [];
      const sample = Array.isArray(tab.sample) ? tab.sample : [];
      lines.push(`### Tab: ${mdCell(tab.name)}`);
      lines.push('');
      lines.push(`- Row count (excluding header): ${Number(tab.rowCount ?? 0)}`);
      lines.push(`- Header row: ${header.length ? header.map((h) => `\`${mdCell(h)}\``).join(', ') : '(none)'}`);
      const flags = flagIdColumns(tab);
      if (flags.length) {
        lines.push('- Columns that LOOK like ids/codes (report only, do not decide):');
        for (const fl of flags) {
          lines.push(`  - col ${fl.column} (\`${mdCell(fl.header)}\`): ${mdCell(fl.reason)}`);
        }
      } else {
        lines.push('- Columns that LOOK like ids/codes: none detected');
      }
      lines.push('');
      if (header.length) {
        lines.push('Sample (up to 3 rows):');
        lines.push('');
        lines.push(`| ${header.map(mdCell).join(' | ')} |`);
        lines.push(`| ${header.map(() => '---').join(' | ')} |`);
        for (const row of sample.slice(0, 3)) {
          const cells = header.map((_, c) => mdCell(Array.isArray(row) ? row[c] : ''));
          lines.push(`| ${cells.join(' | ')} |`);
        }
        lines.push('');
      }
    }
  }
  return lines.join('\n') + '\n';
}

function main() {
  const [, , dumpPath] = process.argv;
  if (!dumpPath) {
    console.error('Usage: node scripts/media/sheets-inventory.mjs <dump.json>');
    process.exit(1);
  }
  const files = JSON.parse(readFileSync(dumpPath, 'utf-8'));
  process.stdout.write(buildReport(files));
  process.exit(0);
}

if (process.argv[1] && process.argv[1].endsWith('sheets-inventory.mjs')) main();
